// EZD-238 Build step 3 (vault/plans/EZD-238.md section 1, Decided "Generator"): writes the DM Mono 400 advance
// table the drawing list measures text with, so no font file is read at run time. Usage: [--out <path>].
// EZD-205a Build step 9 (vault/plans/EZD-205a.md section 1, Decided "Font table"): also the Instrument Sans 600
// table the room labels are measured with, in the same file.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { create } from 'fontkit';

const here = path.dirname(fileURLToPath(import.meta.url));
const fontsDir = path.resolve(here, '../../../app/src/styles/fonts');
const monoFile = path.join(fontsDir, 'dm-mono-latin-400-normal.woff2');
const sansFile = path.join(fontsDir, 'instrument-sans-latin-600-normal.woff2');
const opts = { out: path.resolve(here, '../src/drawing/font-metrics.generated.ts') };

const args = process.argv.slice(2);
for (let i = 0; i < args.length; i += 2) {
  const key = args[i].replace(/^--/, '');
  const value = args[i + 1];
  if (
    !args[i].startsWith('--') ||
    !Object.hasOwn(opts, key) ||
    value === undefined ||
    value.startsWith('--')
  ) {
    process.stderr.write(`bad argument: ${args[i]}\n`);
    process.exit(2);
  }
  opts[key] = path.resolve(value);
}

function table(name, file) {
  const font = create(readFileSync(file));
  const codePoints = [...new Set(font.characterSet)].sort((a, b) => a - b);
  return [
    `export const ${name}: FontMetrics = {`,
    `  unitsPerEm: ${font.unitsPerEm},`,
    `  notdefAdvance: ${font.getGlyph(0).advanceWidth},`,
    '  advances: {',
    ...codePoints.map((cp) => `    ${cp}: ${font.glyphForCodePoint(cp).advanceWidth},`),
    '  },',
    '};',
  ];
}

const lines = [
  '// Generated by packages/geometry/scripts/font-metrics.mjs from',
  '// app/src/styles/fonts/dm-mono-latin-400-normal.woff2 and',
  '// app/src/styles/fonts/instrument-sans-latin-600-normal.woff2.',
  "import type { FontMetrics } from './text';",
  '',
  ...table('DM_MONO_400_METRICS', monoFile),
  '',
  ...table('INSTRUMENT_SANS_600_METRICS', sansFile),
  '',
];
writeFileSync(opts.out, lines.join('\n'));
