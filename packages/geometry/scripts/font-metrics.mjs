// EZD-238 Build step 3 (vault/plans/EZD-238.md section 1, Decided "Generator"): writes the DM Mono 400 advance
// table the drawing list measures text with, so no font file is read at run time. Usage: [--out <path>].
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { create } from 'fontkit';

const here = path.dirname(fileURLToPath(import.meta.url));
const fontFile = path.resolve(here, '../../../app/src/styles/fonts/dm-mono-latin-400-normal.woff2');
const opts = { out: path.resolve(here, '../src/drawing/font-metrics.generated.ts') };

const args = process.argv.slice(2);
for (let i = 0; i < args.length; i += 2) {
  const key = args[i].replace(/^--/, '');
  const value = args[i + 1];
  if (
    !args[i].startsWith('--') ||
    !Object.hasOwn(opts, key) ||
    value === undefined ||
    value.startsWith('--')
  ) {
    process.stderr.write(`bad argument: ${args[i]}\n`);
    process.exit(2);
  }
  opts[key] = path.resolve(value);
}

const font = create(readFileSync(fontFile));
const codePoints = [...new Set(font.characterSet)].sort((a, b) => a - b);
const lines = [
  '// Generated by packages/geometry/scripts/font-metrics.mjs from',
  '// app/src/styles/fonts/dm-mono-latin-400-normal.woff2.',
  "import type { FontMetrics } from './text';",
  '',
  'export const DM_MONO_400_METRICS: FontMetrics = {',
  `  unitsPerEm: ${font.unitsPerEm},`,
  `  notdefAdvance: ${font.getGlyph(0).advanceWidth},`,
  '  advances: {',
  ...codePoints.map((cp) => `    ${cp}: ${font.glyphForCodePoint(cp).advanceWidth},`),
  '  },',
  '};',
  '',
];
writeFileSync(opts.out, lines.join('\n'));
