#!/usr/bin/env node
// Generates acceptance-criteria IDs from each ticket's Done-when text (PROCESS-V2-MIGRATION.md step 4).
//   node vault/tools/gen_acs.mjs            -> rewrites vault/spec/acceptance-criteria.md and the `acs` array of every ticket in tickets.json
//   node vault/tools/gen_acs.mjs --check    -> exit 1 if either file is out of date (used by next_ticket.mjs --check)
// Rules: a ticket's Done-when (its row in vault/tickets/phases/phase-NN.md) is split into sentences; each becomes
// AC-<ticket>-<n>, numbered in order. Sentences starting "Field check" are Josh's manual checks and are tagged (field check).
// Re-run after any phase-file edit (a split, a fix ticket). Hand-edit nothing. From Phase 1 on, Stage 0 writes real ACs
// for the phase; those are added by hand to acceptance-criteria.md under the phase heading with the same ID scheme and
// listed in the ticket's `acs`, and this script leaves a ticket alone when its `acs_source` is "stage-0".
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const vault = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ticketsPath = path.join(vault, 'tickets/tickets.json');
const acPath = path.join(vault, 'spec/acceptance-criteria.md');
const data = JSON.parse(readFileSync(ticketsPath, 'utf8'));

// Done-when text per ticket, from the phase files.
const doneWhen = new Map();
const titles = new Map();
const phaseDir = path.join(vault, 'tickets/phases');
for (const f of readdirSync(phaseDir).filter((n) => /^phase-\d\d\.md$/.test(n)).sort()) {
  for (const line of readFileSync(path.join(phaseDir, f), 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\|\s*(EZD-\d+[a-z]?)\s*\|(.*)\|\s*$/);
    if (!m) continue;
    const cells = m[2].split('|').map((s) => s.trim());
    // columns: Ticket | Scope | Done when | Depends on | Spec ref
    if (cells.length < 3) continue;
    titles.set(m[1], cells[0]);
    doneWhen.set(m[1], cells[2]);
  }
}

const unescape = (s) => s.replace(/\\([_*|])/g, '$1');
function sentences(text) {
  const t = unescape(text).replace(/\s+/g, ' ').trim();
  if (!t) return [];
  // Protect decimals, abbreviations and quoted/parenthesised periods from the split.
  const protectedText = t
    .replace(/(\d)\.(\d)/g, '$1\u0000$2')
    .replace(/\b(e\.g|i\.e|vs|etc|approx|Art|No|Fig|Ch|Sec|St|Rev|ver|min|max|mm|in|ft)\./gi, (m) => m.replace('.', '\u0000'))
    .replace(/\.(?=[a-z0-9_/-]*\.[a-z]{2,4}\b)/g, '\u0000') // file names like gate.mjs, ci.yml
    .replace(/\.(js|ts|mjs|md|json|yml|yaml|png|pdf|dxf|glb|sql|csv|html|svg|usdz|tsx)\b/gi, '\u0000$1');
  // Split at sentence ends and at top-level semicolons (a semicolon inside parentheses stays).
  const parts = [];
  let depth = 0, cur = '';
  for (let i = 0; i < protectedText.length; i++) {
    const ch = protectedText[i];
    if (ch === '(') depth++;
    if (ch === ')') depth = Math.max(0, depth - 1);
    cur += ch;
    const next = protectedText[i + 1] || '';
    if (depth === 0 && ((/[.!?]/.test(ch) && /\s/.test(next) && /[A-Z"“(`]/.test(protectedText.slice(i + 1).trimStart()[0] || '')) || (ch === ';' && /\s/.test(next)))) {
      parts.push(cur); cur = '';
    }
  }
  if (cur.trim()) parts.push(cur);
  return parts.map((s) => s.replace(/\u0000/g, '.').replace(/;$/, '').trim()).filter(Boolean);
}

const perPhase = new Map();
let changed = false;
const acsById = new Map();
for (const t of data.tickets) {
  const dw = doneWhen.get(t.id);
  if (dw === undefined) { console.error(`gen_acs: ${t.id} has no row in a phase file`); process.exit(1); }
  if (t.acs_source === 'stage-0' && Array.isArray(t.acs) && t.acs.length) { acsById.set(t.id, t.acs.map((id, i) => ({ id, text: '(Stage 0 AC; see acceptance-criteria.md)', field: false }))); continue; }
  const list = sentences(dw).map((text, i) => ({ id: `AC-${t.id}-${i + 1}`, text, field: /^field check/i.test(text) }));
  if (!list.length) list.push({ id: `AC-${t.id}-1`, text: dw.trim(), field: false });
  acsById.set(t.id, list);
  const ids = list.map((a) => a.id);
  if (JSON.stringify(t.acs || []) !== JSON.stringify(ids)) { changed = true; t.acs = ids; t.acs_source = 'done-when'; }
  if (!perPhase.has(t.phase)) perPhase.set(t.phase, []);
  perPhase.get(t.phase).push(t);
}

let md = '# Acceptance criteria\n\n';
md += 'Generated by `vault/tools/gen_acs.mjs` from each ticket\'s Done-when (its row in `vault/tickets/phases/phase-NN.md`); do not hand-edit generated rows. One row per testable sentence, `AC-<ticket>-<n>`. Rows marked *(field check)* are Josh\'s manual checks at the phase field check, not automated tests. From Phase 1 on, Stage 0 writes the phase\'s real ACs (PROCESS.md section 5); a ticket whose `acs_source` in `tickets.json` is `stage-0` keeps its hand-written rows here. `vault/tickets/TRACE.md` maps each AC to its ticket and tests.\n\n';
let total = 0;
for (const phase of [...perPhase.keys()].sort((a, b) => a - b)) {
  md += `## Phase ${phase}\n\n| AC | Ticket | Criterion |\n| --- | --- | --- |\n`;
  for (const t of perPhase.get(phase)) {
    for (const a of acsById.get(t.id)) {
      md += `| ${a.id} | ${t.id} ${titles.get(t.id) || t.title} | ${a.text.replace(/\|/g, '\\|')}${a.field ? ' *(field check)*' : ''} |\n`;
      total++;
    }
  }
  md += '\n';
}
md += `Total: ${total} criteria across ${data.tickets.length} tickets.\n`;

const args = process.argv.slice(2);
if (args.includes('--check')) {
  let current = '';
  try { current = readFileSync(acPath, 'utf8'); } catch {}
  if (changed || current !== md) { console.log('ACCEPTANCE CRITERIA OUT OF DATE: run node vault/tools/gen_acs.mjs'); process.exit(1); }
  console.log(`ACs OK: ${total}`);
  process.exit(0);
}
writeFileSync(ticketsPath, JSON.stringify(data, null, 1) + '\n'); // 1-space indent matches the Oct 11 export
writeFileSync(acPath, md);
console.log(`gen_acs: ${total} criteria for ${data.tickets.length} tickets -> ${path.relative(process.cwd(), acPath)}; tickets.json acs ${changed ? 'updated' : 'unchanged'}`);
