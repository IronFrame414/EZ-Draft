// EZD-1910 (editor plan 5.4 "keep the registry index from becoming the next hot file"): writes each generated
// registry index from its folder listing, sorted, so two branches that add different features produce the same file
// and a merge conflict is settled by running this script again.
//
//   node app/tools/gen-registry.mjs          write every index
//   node app/tools/gen-registry.mjs --check  exit 1 when an index is stale, or when anything it imports reaches
//                                            app/src/lazy/ statically (EZD-120c B11: no lazy code in the editor entry)
//
// The unit test app/src/editor/features/index.generated.test.ts runs the same checks.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const APP_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** The generated indexes. `dir` is relative to app/. Each listed file exports `exportName`. */
export const TARGETS = [
  {
    dir: 'src/editor/features',
    exportName: 'feature',
    listName: 'features',
    type: 'EditorFeature',
    typeFrom: './types',
  },
  // EZD-1914 (editor plan 5.3 "ceiling/tools/"): one click receiver per ceiling tool.
  {
    dir: 'src/editor/ceiling/tools',
    exportName: 'tool',
    listName: 'ceilingTools',
    type: 'CeilingTool',
    typeFrom: './types',
  },
];

export const INDEX_FILE = 'index.generated.ts';

const NOT_LISTED = new Set(['types.ts', INDEX_FILE]);

/** The folder's entry files, sorted by code point (the same on every machine). */
export function listEntries(dir) {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile())
    .map((e) => e.name)
    .filter((n) => /\.tsx?$/.test(n) && !/\.test\.tsx?$/.test(n) && !n.endsWith('.d.ts') && !NOT_LISTED.has(n))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

function identifierOf(file) {
  const base = file.replace(/\.tsx?$/, '');
  const camel = base.replace(/[^A-Za-z0-9_$]+([A-Za-z0-9_$])?/g, (_, c) => (c ? c.toUpperCase() : ''));
  return /^[A-Za-z_$]/.test(camel) ? camel : `_${camel}`;
}

/** The text of `target`'s index for the files now in `dir`. */
export function renderIndex(target, dir) {
  const files = listEntries(dir);
  const lines = [
    `// Generated by app/tools/gen-registry.mjs from the files in this folder. Do not edit: run`,
    `// \`node app/tools/gen-registry.mjs\` after adding or removing a file.`,
    `import type { ${target.type} } from '${target.typeFrom}';`,
  ];
  const names = [];
  for (const f of files) {
    const id = identifierOf(f);
    names.push(id);
    lines.push(`import { ${target.exportName} as ${id} } from './${f.replace(/\.tsx?$/, '')}';`);
  }
  lines.push('');
  if (names.length === 0) {
    lines.push(`export const ${target.listName}: readonly ${target.type}[] = [];`);
  } else {
    lines.push(`export const ${target.listName}: readonly ${target.type}[] = [`);
    for (const n of names) lines.push(`  ${n},`);
    lines.push('].sort((a, b) => a.order - b.order);');
  }
  return lines.join('\n') + '\n';
}

/** True when the index file in `dir` is missing or differs from what `renderIndex` makes now. */
export function isStale(target, dir) {
  const file = path.join(dir, INDEX_FILE);
  if (!fs.existsSync(file)) return true;
  return fs.readFileSync(file, 'utf8') !== renderIndex(target, dir);
}

// Static imports and re-exports of one source; `import type`, `export type` and `import()` are left out (they put no
// code in the bundle that imports them).
const STATIC_IMPORT = /(?:^|[;\n}])\s*(?:import|export)\s+(?!type\b)(?:[\w*{}\s,$]+?\s+from\s*)?['"]([^'"\n]+)['"]/g;

function stripComments(source) {
  return source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:'"\\])\/\/.*$/gm, '$1');
}

export function staticSpecifiers(source) {
  const out = [];
  for (const m of stripComments(source).matchAll(STATIC_IMPORT)) out.push(m[1]);
  return out;
}

const EXTENSIONS = ['.ts', '.tsx', '.mts', '.js', '.jsx', '.mjs'];

function asFile(p) {
  try {
    return fs.statSync(p).isFile() ? p : null;
  } catch {
    return null;
  }
}

/** The file `spec` names from `fromFile`, or null for a package or a name that does not resolve. */
export function resolveSpecifier(spec, fromFile, srcRoot) {
  let base;
  if (spec.startsWith('.')) base = path.resolve(path.dirname(fromFile), spec);
  else if (spec.startsWith('@/')) base = path.join(srcRoot, spec.slice(2));
  else return null;
  const candidates = [base];
  if (/\.m?jsx?$/.test(base)) candidates.push(base.replace(/\.m?jsx?$/, '.ts'), base.replace(/\.m?jsx?$/, '.tsx'));
  for (const ext of EXTENSIONS) candidates.push(base + ext);
  for (const ext of EXTENSIONS) candidates.push(path.join(base, 'index' + ext));
  for (const c of candidates) {
    const f = asFile(c);
    if (f) return f;
  }
  return null;
}

/**
 * Every file under `lazyRoot` that `entry` reaches through static imports, each with the chain of files that
 * leads to it (entry first). Empty when nothing reaches it.
 * @param {string} entry
 * @param {{ srcRoot: string, lazyRoot: string }} roots
 * @returns {string[][]}
 */
export function lazyReaches(entry, { srcRoot, lazyRoot }) {
  const lazyPrefix = path.resolve(lazyRoot) + path.sep;
  const parent = new Map([[path.resolve(entry), null]]);
  const queue = [path.resolve(entry)];
  const found = [];
  while (queue.length > 0) {
    const file = queue.shift();
    if (file.startsWith(lazyPrefix)) {
      const chain = [];
      for (let f = file; f !== null; f = parent.get(f)) chain.unshift(f);
      found.push(chain);
      continue;
    }
    if (!/\.(m?[jt]sx?)$/.test(file)) continue;
    for (const spec of staticSpecifiers(fs.readFileSync(file, 'utf8'))) {
      const next = resolveSpecifier(spec, file, srcRoot);
      if (next === null || parent.has(next)) continue;
      parent.set(next, file);
      queue.push(next);
    }
  }
  return found;
}

function main(argv) {
  const check = argv.includes('--check');
  const srcRoot = path.join(APP_ROOT, 'src');
  const lazyRoot = path.join(srcRoot, 'lazy');
  let failed = false;
  for (const target of TARGETS) {
    const dir = path.join(APP_ROOT, target.dir);
    const file = path.join(dir, INDEX_FILE);
    if (!check) {
      fs.writeFileSync(file, renderIndex(target, dir));
      console.log(`wrote ${path.relative(APP_ROOT, file)}`);
      continue;
    }
    if (isStale(target, dir)) {
      console.error(`${path.relative(APP_ROOT, file)} is stale: run node app/tools/gen-registry.mjs`);
      failed = true;
    }
    for (const chain of lazyReaches(file, { srcRoot, lazyRoot })) {
      console.error(`static import of lazy code: ${chain.map((f) => path.relative(APP_ROOT, f)).join(' -> ')}`);
      failed = true;
    }
  }
  if (failed) process.exitCode = 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
