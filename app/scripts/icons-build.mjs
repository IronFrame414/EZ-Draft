import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const icon = path.resolve(here, '../src/components/icon');
const opts = {
  src: path.join(icon, 'svg'),
  list: path.join(icon, 'icons.json'),
  sprite: path.resolve(here, '../public/icons/sprite.svg'),
  names: path.join(icon, 'icon-names.generated.ts'),
};

const args = process.argv.slice(2);
const bad = [];
for (let i = 0; i < args.length; i += 2) {
  const key = args[i].replace(/^--/, '');
  const value = args[i + 1];
  if (
    !args[i].startsWith('--') ||
    !Object.hasOwn(opts, key) ||
    value === undefined ||
    value.startsWith('--')
  ) {
    bad.push(`bad argument: ${args[i]}`);
    break;
  }
  opts[key] = path.resolve(value);
}
if (bad.length) {
  process.stderr.write(bad.join('\n') + '\n');
  process.exit(1);
}

const problems = [];
let list = [];
try {
  list = JSON.parse(readFileSync(opts.list, 'utf8'));
  if (!Array.isArray(list) || !list.every((n) => typeof n === 'string')) {
    problems.push(`${opts.list}: not a JSON array of strings`);
    list = [];
  }
} catch (e) {
  problems.push(`${opts.list}: cannot read list (${e.message})`);
}

const seen = new Set();
list.forEach((name, i) => {
  if (!/^[a-z0-9_]+(-fill)?$/.test(name)) problems.push(`${name}: invalid name`);
  if (seen.has(name)) problems.push(`${name}: repeated`);
  seen.add(name);
  if (i > 0 && !(list[i - 1] < name) && list[i - 1] !== name) problems.push(`${name}: unsorted`);
});

const symbols = [];
for (const name of list) {
  if (!/^[a-z0-9_]+(-fill)?$/.test(name)) continue;
  const file = path.join(opts.src, `${name}.svg`);
  if (!existsSync(file)) {
    problems.push(`${name}: missing source ${file}`);
    continue;
  }
  const text = readFileSync(file, 'utf8');
  const m = text.match(
    /^\s*(?:<\?xml[^>]*\?>\s*)?<svg\b([^>]*)>\s*((?:<path d="[^"]*"\s*\/>\s*)+)<\/svg>\s*$/,
  );
  const vb = m && m[1].match(/\sviewBox="([^"]+)"/);
  if (!m || !vb) {
    problems.push(`${name}: source svg not allowed (${file})`);
    continue;
  }
  const paths = [...m[2].matchAll(/<path d="([^"]*)"\s*\/>/g)].map((p) => `<path d="${p[1]}"/>`);
  symbols.push(`<symbol id="${name}" viewBox="${vb[1]}">${paths.join('')}</symbol>`);
}

if (problems.length) {
  process.stderr.write(problems.join('\n') + '\n');
  process.exit(1);
}

const sprite =
  [
    '<svg xmlns="http://www.w3.org/2000/svg">',
    '<!-- Generated by app/scripts/icons-build.mjs from icons.json; do not edit. Icons from github.com/google/material-design-icons, Apache-2.0 (app/src/components/icon/svg/LICENSE). -->',
    ...symbols,
    '</svg>',
  ].join('\n') + '\n';
const names =
  [
    '// Generated by app/scripts/icons-build.mjs from icons.json; do not edit.',
    'export const ICON_NAMES = [',
    ...list.map((n) => `  '${n}',`),
    '] as const;',
    'export type IconName = (typeof ICON_NAMES)[number];',
  ].join('\n') + '\n';

for (const [file, body] of [
  [opts.sprite, sprite],
  [opts.names, names],
]) {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, body);
}
