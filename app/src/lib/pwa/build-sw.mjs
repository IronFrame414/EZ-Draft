// EZD-134 (architecture "Device storage": workbox-build generates the worker): writes app/public/sw.js, the
// worker EZD-013 registers at /sw.js with scope /. Runtime routes only, no build manifest: the spec caches what was
// loaded once (11 Offline "cached by the service worker after first load"): after each load the page names what it
// loaded and the worker stores it (sw-rules.mjs onWarmMessage, copied in ahead of the Workbox code). The routes
// match only while the device is offline and answer from the cache; online the worker answers nothing. The API, auth links, invites and dev pages are never answered. Run
// `pnpm --filter app sw` after a change here or in sw-rules.mjs; sw-file.test.ts fails while public/sw.js is out
// of date.
import { generateSW } from 'workbox-build';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  PROJECT_CACHE,
  SHELL_CACHE,
  STATIC_CACHE,
  WORKER_CONSTANTS,
  WORKER_FUNCTIONS,
  offlineProjectPage,
  offlineShellPage,
  offlineStaticFile,
} from './sw-rules.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const SW_PATH = path.join(here, '..', '..', '..', 'public', 'sw.js');

// Next pages answer with Vary on the router headers; a page load offline must still find its copy.
const fromCache = (cacheName) => ({ cacheName, matchOptions: { ignoreVary: true } });

export function swConfig(swDest, emptyDir) {
  return {
    swDest,
    globDirectory: emptyDir,
    globPatterns: [],
    inlineWorkboxRuntime: true,
    mode: 'production',
    sourcemap: false,
    skipWaiting: true,
    clientsClaim: true,
    runtimeCaching: [
      { urlPattern: offlineShellPage, handler: 'CacheOnly', options: fromCache(SHELL_CACHE) },
      { urlPattern: offlineProjectPage, handler: 'CacheOnly', options: fromCache(PROJECT_CACHE) },
      { urlPattern: offlineStaticFile, handler: 'CacheOnly', options: fromCache(STATIC_CACHE) },
    ],
  };
}

// The cache work of sw-rules.mjs as worker source: its constants, its functions and the message listener. Top
// level, so the Workbox routes (copied after it) can call the path rules.
export function workerCode() {
  const constants = Object.entries(WORKER_CONSTANTS).map(
    ([name, value]) => `const ${name} = ${JSON.stringify(value)};`,
  );
  const functions = WORKER_FUNCTIONS.map((f) => f.toString().replace(/^export /, ''));
  const listener = `self.addEventListener('install', addNetworkRoutes);
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === WARM_MESSAGE && !event.data.done) {
    event.waitUntil(onWarmMessage(event.data).then(() => replyWarmed(event.source)));
  }
});`;
  return `${[...constants, ...functions, listener].join('\n')}\n`;
}

// Workbox output is minified; the header names its source and keeps it out of lint.
export const SW_HEADER =
  '/* eslint-disable */\n// Generated by app/src/lib/pwa/build-sw.mjs (EZD-134, Workbox). Do not edit: run `pnpm --filter app sw`.\n';

export async function buildServiceWorker(swDest = SW_PATH) {
  const { mkdtemp, readFile, rm, writeFile } = await import('node:fs/promises');
  const { tmpdir } = await import('node:os');
  const empty = await mkdtemp(path.join(tmpdir(), 'ezd-sw-'));
  try {
    const result = await generateSW(swConfig(swDest, empty));
    await writeFile(swDest, SW_HEADER + workerCode() + (await readFile(swDest, 'utf8')));
    return result;
  } finally {
    await rm(empty, { recursive: true, force: true });
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  // `--out <file>` writes elsewhere (sw-file.test.ts compares that with public/sw.js).
  const at = process.argv.indexOf('--out');
  const out = at > 0 && process.argv[at + 1] ? path.resolve(process.argv[at + 1]) : SW_PATH;
  const { warnings } = await buildServiceWorker(out);
  for (const w of warnings) process.stderr.write(`${w}\n`);
  process.stdout.write(`wrote ${path.relative(process.cwd(), out)}\n`);
}
